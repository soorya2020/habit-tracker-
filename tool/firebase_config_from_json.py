"""Writes lib/firebase_config.dart from a Firebase google-services.json.

Usage: python3 tool/firebase_config_from_json.py path/to/google-services.json
"""
import json
import sys

PACKAGE = 'club.onepercent.one_percent_club'

j = json.load(open(sys.argv[1]))
info = j['project_info']
client = next(c for c in j['client']
              if c['client_info']['android_client_info']['package_name'] == PACKAGE)
web = [o['client_id'] for o in client.get('oauth_client', []) if o.get('client_type') == 3]
web += [o['client_id'] for o in client['services']['appinvite_service'].get('other_platform_oauth_client', [])
        if o.get('client_type') == 3]
if not web:
    sys.exit('No web OAuth client in this file. Turn on Google sign-in in Firebase, then download it again.')

out = f"""import 'package:firebase_core/firebase_core.dart';

/// Values from the Firebase project's google-services.json
/// (generated by tool/firebase_config_from_json.py). These identify the
/// project; access is controlled by Firebase Auth and firestore.rules.
const FirebaseOptions? firebaseOptions = FirebaseOptions(
  apiKey: '{client['api_key'][0]['current_key']}',
  appId: '{client['client_info']['mobilesdk_app_id']}',
  messagingSenderId: '{info['project_number']}',
  projectId: '{info['project_id']}',
  storageBucket: '{info.get('storage_bucket', '')}',
);

/// The "web" OAuth client, which Google sign-in on Android needs to issue
/// an ID token for Firebase.
const String? googleServerClientId = '{web[0]}';
"""
open('lib/firebase_config.dart', 'w').write(out)
print('ok', info['project_id'])
